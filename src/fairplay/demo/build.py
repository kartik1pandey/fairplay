"""Public demo (design §9, §11): one static page, synthetic accounts only.

The page shows what a reviewer would see: a ranked weekly queue and a case file per account. Every
account on it was generated by the synthetic benchmark, so nothing on it describes a real player.
Aggregate real-data results are shown as published in results/results.json.

Static on purpose: no server, so there is no lookup endpoint to abuse and nothing to rate-limit.

uv run python -m fairplay.demo.build        -> demo/index.html
"""

import json
from pathlib import Path

import numpy as np

from fairplay.casefiles.peers import PeerReference
from fairplay.casefiles.template import DISCLAIMER, build_case
from fairplay.features.game_features import FEATURE_VERSION
from fairplay.runs import RUNS
from fairplay.synthetic import score as sc
from fairplay.synthetic.run_synthetic import CUTOFF, MODEL_TABLE, OUT

DEMO = Path("demo")
PEERS = Path("data/processed/peer_stats_clock30.parquet")
SHOWN = 30
LABELS = {"control": "honest control", "A": "engine A (blunt)", "B": "engine B (moderate)",
          "C": "engine C (careful, held out)"}


def latest_synthetic_run() -> tuple[str, dict]:
    runs = sorted(p for p in RUNS.glob("*_synthetic_score") if (p / "metrics.json").exists())
    if not runs:
        raise SystemExit("score the synthetic benchmark first (run_synthetic score)")
    run = runs[-1]
    return run.name, json.loads((run / "metrics.json").read_text(encoding="utf-8"))


def strategies_in(metrics: dict) -> list[str]:
    """Strategies of the latest scored run; C appears only once it has been scored."""
    return sorted(metrics["recall"], key=lambda s: ("control", "A", "B", "C").index(s))


def check_synthetic_only(obj) -> None:
    """Fail closed: every account id on the page must be a synthetic one."""
    text = json.dumps(obj)
    for key in ("account", "account_id"):
        for part in text.split(f'"{key}": "')[1:]:
            if not part.startswith("syn-"):
                raise ValueError(f"non-synthetic {key} in demo data")


def build() -> Path:
    from fairplay.casefiles.run_casefiles import chosen_model, display_score

    run_name, metrics = latest_synthetic_run()
    strategies = strategies_in(metrics)
    files = [OUT / "player_games" / f"strategy={s}.parquet" for s in strategies]
    ages = {a["account_id"]: a["account_age_days"] for s in strategies
            for a in json.loads((OUT / f"accounts_{s}.json").read_text(encoding="utf-8"))}
    feats = sc.synthetic_features(files, CUTOFF, PEERS)
    split = sc.to_split(feats, ages, CUTOFF)
    model = chosen_model()
    score = np.asarray(model.score(split), dtype=float)
    shown = np.asarray(display_score(model, split), dtype=float)
    threshold = metrics["threshold"]["threshold"]
    ref = PeerReference.from_model_table(MODEL_TABLE)
    versions = {"model": model.name, "features": FEATURE_VERSION, "policy": "c0.5-m1.0"}

    queue = []
    for rank, i in enumerate(np.argsort(-score, kind="stable")[:SHOWN], 1):
        row = dict(feats[i])
        case = build_case(row, shown[i], ref, versions)
        queue.append({"rank": rank, "account": case["account"],
                      "generated_as": LABELS[sc.strategy_of(case["account"])],
                      "rating": int(row["rating_at_cutoff"]), "games": int(row["games_in_window"]),
                      "probability": round(float(shown[i]), 4),
                      "above_real_cut": bool(score[i] >= threshold), "case": case})

    real = json.loads(Path("results/results.json").read_text(encoding="utf-8"))
    data = {
        "disclaimer": DISCLAIMER, "cutoff": str(CUTOFF.date()), "synthetic_run": run_name,
        "population": {LABELS[s]: int(metrics["recall"][s]["n"]) for s in strategies},
        "synthetic": {
            "lightgbm": {LABELS[s]: {"share_above": r.get("synthetic_recall",
                                                          r.get("control_false_alarm")),
                                     "ci95": r["wilson_95"]}
                         for s, r in metrics["recall"].items()},
            "rule": {LABELS[s]: r.get("synthetic_recall", r.get("control_false_alarm"))
                     for s, r in metrics["rule"]["recall"].items()},
            "auc_lightgbm": {LABELS[s]: v for s, v in metrics["auc_vs_control"].items()},
            "auc_rule": {LABELS[s]: v for s, v in metrics["rule"]["auc_vs_control"].items()},
            "unrealistic_features": metrics["realism"]["features_ks_above_limit"]},
        "real_results": [{"claim": r["claim"], "split": r["split"], "value": r["value_num"],
                          "low": r["low_num"], "high": r["high_num"]} for r in real],
        "queue": queue,
    }
    check_synthetic_only(data)
    DEMO.mkdir(exist_ok=True)
    template = (Path(__file__).parent / "page.html").read_text(encoding="utf-8")
    payload = json.dumps(data, default=str).replace("</", "<\\/")
    out = DEMO / "index.html"
    tmp = out.with_suffix(".html.tmp")
    tmp.write_text(template.replace("/*DATA*/null", payload), encoding="utf-8")
    tmp.replace(out)
    return out


def main() -> None:
    print(build())


if __name__ == "__main__":
    main()
