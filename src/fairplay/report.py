"""Canonical results table (design §12): generated from a NAMED list of runs, never typed by hand.

results/runs.json names each row: {"rows": [{"experiment": "R", "split": "test",
  "claim": "...", "run": "<run_id>", "value": "a.b.c", "low": "...", "high": "..."}]}
`build` reads runs/<run>/metrics.json, follows the dotted paths, and writes results/results.md
(+ .json). runs/ stays local (it may hold more detail than is publishable); the generated table
is committed. `check` (CI) fails if the README's results block differs from results/results.md,
so no number in the README can drift from the runs that produced it.

uv run python -m fairplay.report build
uv run python -m fairplay.report check README.md
"""

import argparse
import json
import sys
from pathlib import Path

from fairplay.runs import RUNS

RESULTS = Path("results")
START, END = "<!-- results:start -->", "<!-- results:end -->"
EMPTY = "_No final runs yet. Every number here is generated by `fairplay.report build`._"


def lookup(metrics: dict, path: str):
    v = metrics
    for part in path.split("."):
        v = v[int(part)] if isinstance(v, list) else v[part]
    return v


def fmt(x) -> str:
    if x is None:
        return "–"
    if isinstance(x, float):
        return f"{x:.3f}"
    return str(x)


def table(spec: dict, runs: Path = RUNS) -> tuple[str, list[dict]]:
    rows = []
    for r in spec.get("rows", []):
        metrics = json.loads((runs / r["run"] / "metrics.json").read_text(encoding="utf-8"))
        rows.append({**r, "value_num": lookup(metrics, r["value"]),
                     "low_num": lookup(metrics, r["low"]) if r.get("low") else None,
                     "high_num": lookup(metrics, r["high"]) if r.get("high") else None})
    if not rows:
        return EMPTY + "\n", rows
    lines = ["| Experiment | Split | Claim | Value | 95% CI | Run |", "|---|---|---|---|---|---|"]
    for r in rows:
        ci = (f"{fmt(r['low_num'])} – {fmt(r['high_num'])}"
              if r["low_num"] is not None else "–")
        lines.append(f"| {r['experiment']} | {r['split']} | {r['claim']} | "
                     f"{fmt(r['value_num'])} | {ci} | `{r['run']}` |")
    return "\n".join(lines) + "\n", rows


def build(results: Path = RESULTS, runs: Path = RUNS) -> str:
    spec_path = results / "runs.json"
    spec = json.loads(spec_path.read_text(encoding="utf-8")) if spec_path.exists() else {}
    md, rows = table(spec, runs)
    results.mkdir(exist_ok=True)
    (results / "results.md").write_text(md, encoding="utf-8")
    (results / "results.json").write_text(json.dumps(rows, indent=2, default=str),
                                          encoding="utf-8")
    return md


def readme_block(readme: Path) -> str:
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no results block ({START} ... {END})")
    return text.split(START, 1)[1].split(END, 1)[0].strip("\n") + "\n"


def check(readme: Path, results: Path = RESULTS) -> bool:
    return readme_block(readme) == (results / "results.md").read_text(encoding="utf-8")


def sync(readme: Path, results: Path = RESULTS) -> None:
    """Paste the generated table into the README block (the only way numbers get there)."""
    text = readme.read_text(encoding="utf-8")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    md = (results / "results.md").read_text(encoding="utf-8")
    readme.write_text(f"{head}{START}\n{md}{END}{tail}", encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("cmd", choices=["build", "check", "sync"])
    p.add_argument("readme", nargs="?", type=Path, default=Path("README.md"))
    args = p.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252 (no "−")
    if args.cmd == "build":
        print(build())
    elif args.cmd == "sync":
        sync(args.readme)
    elif not check(args.readme):
        print("README results block differs from results/results.md: run "
              "`fairplay.report build` then `fairplay.report sync`")
        sys.exit(1)


if __name__ == "__main__":
    main()
